import "server-only";

/**
 * Einfaches In-Memory-Rate-Limit (Sliding Window) pro Schlüssel.
 * Hinweis: Auf Serverless-Plattformen gilt das Limit pro Instanz. Für hohe Last
 * kann es später durch einen zentralen Speicher (z. B. Upstash Redis) ersetzt werden.
 */
const buckets = new Map<string, number[]>();

export function rateLimit(key: string, limit: number, windowMs: number): { ok: boolean; retryAfter: number } {
  const now = Date.now();
  const hits = (buckets.get(key) ?? []).filter((t) => now - t < windowMs);
  if (hits.length >= limit) {
    buckets.set(key, hits);
    return { ok: false, retryAfter: Math.ceil((windowMs - (now - hits[0]!)) / 1000) };
  }
  hits.push(now);
  buckets.set(key, hits);
  if (buckets.size > 5000) {
    for (const [k, v] of buckets) if (!v.some((t) => now - t < windowMs)) buckets.delete(k);
  }
  return { ok: true, retryAfter: 0 };
}
